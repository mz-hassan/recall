import { test, expect } from '@playwright/test';

test.use({ launchOptions: { args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] }, permissions: ['microphone'], reducedMotion: 'reduce' });

test('CS50 uses the regular course, materials, timeline, microphone, and moment detail flow', async ({ page, request }, testInfo) => {
  test.setTimeout(90000);
  page.on('pageerror', error => { throw error; });
  const audioDestinations = [];
  await page.addInitScript(() => sessionStorage.setItem('recall-course-profile', JSON.stringify({ email: 'cs50-test@example.edu', role: 'student', courseId: 'ai' })));
  await page.route('https://fonts.googleapis.com/**', route => route.abort());
  await page.route('https://fonts.gstatic.com/**', route => route.abort());
  await page.route('**/api/lectures/cs50/0/slide-coaching', async route => {
    const response = await route.fetch();
    const notes = await response.json();
    if (response.ok()) notes.spec.equations = [{ expression: 'n=2^b', explanation: 'Explicit equation rendering fixture.', variables: [{ symbol: 'n', definition: 'Number of representable values' }, { symbol: 'b', definition: 'Number of bits' }] }];
    await route.fulfill({ response, json: notes });
  });
  page.on('request', request => { if (request.url().includes('/microphone/audio')) audioDestinations.push(new URL(request.url()).origin); });
  await page.goto('/#courses', { waitUntil: 'domcontentloaded' });
  await expect(page.locator('a[href="cs50.html"]')).toHaveCount(0);
  await page.getByRole('link', { name: '+ Find or add a course', exact: true }).click();
  await page.getByRole('searchbox').fill('cs50');
  await page.getByRole('button', { name: 'Add course +', exact: true }).click();
  await expect(page).toHaveURL(/#course\/cs50$/);
  await page.getByRole('link', { name: 'Course material for Lecture 00', exact: true }).click();
  await expect(page).toHaveURL(/#lecture\/cs50\/0$/);
  await expect(page.getByRole('link', { name: 'Lecture 0 notes', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Lecture 0 video', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Start live lecture', exact: false }).click();
  await expect(page).toHaveURL(/lecture\.html\?lecture=0&course=cs50&mode=microphone/);
  await expect(page.locator('#lectureInfo')).toContainText('CS50x');
  await page.getByRole('button', { name: 'Start listening', exact: true }).click();
  await expect(page.getByText('● Listening on this laptop', { exact: true })).toBeVisible();
  await expect(page.locator('.moment.current')).toBeVisible({ timeout: 25000 });
  await page.getByRole('button', { name: 'Stop listening', exact: true }).click();
  await expect(page.getByText('Microphone off', { exact: true })).toBeVisible({ timeout: 15000 });
  await page.locator('.moment.current').click();
  await expect(page.getByRole('region', { name: 'Expanded lecture moment', exact: true })).toBeVisible();
  await expect(page.locator('.pilot-pdf-host canvas')).toBeVisible({ timeout: 15000 });
  await expect(page.locator('.pilot-highlight').first()).toBeVisible({ timeout: 15000 });
  await page.locator('.equation-variables>span').first().focus();
  await expect(page.getByRole('tooltip').first()).toBeVisible();
  await page.getByRole('button', { name: 'Animate explanation', exact: true }).click();
  await expect(page.locator('.pilot-table tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.getByRole('button', { name: 'Fill next row', exact: true }).click();
  await expect(page.locator('.pilot-table tbody tr')).toHaveCount(2);
  await page.screenshot({ path: testInfo.outputPath('cs50-integrated.png'), fullPage: true });
  const snapshot = await (await request.get('/api/lectures/cs50/0/moments')).json();
  expect(snapshot.session.state).toBe('completed');
  expect(snapshot.moments.some(moment => moment.quote.includes('Binary search'))).toBeTruthy();
  expect(snapshot.moments.every(moment => moment.sources.every(source => source.path.startsWith('microphone/')))).toBeTruthy();
  expect(new Set(audioDestinations)).toEqual(new Set(['http://127.0.0.1:4175']));
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(page.locator('.moment.current')).toBeVisible();
  await expect(page.getByText('Microphone off', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
});

test('CS50 reference replay uses the same lecture view and keeps AI Alignment sessions separate', async ({ page, request }) => {
  await page.addInitScript(() => sessionStorage.setItem('recall-course-profile', JSON.stringify({ email: 'reference-test@example.edu', role: 'student', courseId: 'cs50' })));
  await page.route('https://fonts.googleapis.com/**', route => route.abort());
  await page.route('https://fonts.gstatic.com/**', route => route.abort());
  const ai = await (await request.get('/api/lectures/ai/2/moments')).json();
  await page.goto('/#lecture/cs50/0', { waitUntil: 'domcontentloaded' });
  await page.getByRole('link', { name: 'Replay reference transcript', exact: false }).click();
  await expect(page.locator('#lectureInfo')).toContainText('CS50x');
  await expect(page.locator('.moment.current')).toBeVisible({ timeout: 15000 });
  await expect(page.getByRole('button', { name: 'Play simulated lecture', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Start listening', exact: true })).toHaveCount(0);
  const reference = await (await request.get('/api/lectures/cs50/0/moments')).json();
  expect(reference.moments[0].sources.every(source => source.path === 'lecture0/transcript.vtt')).toBeTruthy();
  expect((await (await request.get('/api/lectures/ai/2/moments')).json()).runId).toBe(ai.runId);
});
